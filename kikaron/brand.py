# --- 8. Kikaron colours: indigo accent, paper background, white cards -------

INDIGO, INDIGO_DARK = (0x3A, 0x4B, 0x94), (0x9A, 0xA8, 0xE6)
COLOUR_MAP = {  # (appearance, upstream rgb) -> Kikaron rgb
    ("light", (0x17, 0x5D, 0xDC)): INDIGO,               # Bitwarden blue: buttons, links, tint
    ("dark", (0x65, 0xAB, 0xFF)): INDIGO_DARK,
    ("light", (0xF3, 0xF6, 0xF9)): (0xF5, 0xF2, 0xEC),   # backgroundPrimary / splash: paper
    ("light", (0xDB, 0xE5, 0xF6)): (0xE1, 0xE4, 0xF1),   # tertiary / illustration wash
    ("light", (0x02, 0x0F, 0x66)): (0x23, 0x2D, 0x5E),   # alert background / illustration outline
    ("dark", (0x17, 0x5D, 0xDC)): INDIGO,                # illustration outline (dark)
}
COLOUR_DIRS = ["BitwardenResources/Colors.xcassets", "Bitwarden/Application/Support/Assets.xcassets"]


def colours():
    import json
    for base in COLOUR_DIRS:
        for dirpath, _, files in sorted(os.walk(p(base))):
            if not dirpath.endswith(".colorset") or "Contents.json" not in files:
                continue
            path = os.path.join(dirpath, "Contents.json")
            with open(path) as fh:
                data = json.load(fh)
            changed = False
            for entry in data.get("colors", []):
                comp = entry.get("color", {}).get("components")
                if not comp or not str(comp.get("red", "")).startswith("0x"):
                    continue
                look = "dark" if any(a.get("value") == "dark" for a in entry.get("appearances", [])) else "light"
                rgb = tuple(int(comp[k], 16) for k in ("red", "green", "blue"))
                new = COLOUR_MAP.get((look, rgb))
                if new:
                    comp.update({k: f"0x{v:02X}" for k, v in zip(("red", "green", "blue"), new)})
                    changed = True
            if changed:
                with open(path, "w") as fh:
                    json.dump(data, fh, indent=2, separators=(",", " : "))  # Xcode style
                    fh.write("\n")


