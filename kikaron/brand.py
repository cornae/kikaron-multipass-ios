# --- 3. Entitlements --------------------------------------------------------

def entitlements():
    def app(d):
        d.pop("aps-environment", None)  # no push for now; the app syncs on open
        d.pop("com.apple.developer.nfc.readersession.formats", None)
        d.pop("com.apple.developer.ubiquity-container-identifiers", None)
        d["com.apple.developer.associated-domains"] = [f"webcredentials:{SERVER_HOST}"]
        d["com.apple.security.application-groups"] = ["group.$(BASE_BUNDLE_ID)"]
    edit_plist("Bitwarden/Application/Support/Bitwarden.entitlements", app)


# --- 4. Info.plists: names, export compliance, background modes -------------

def info_plists():
    def app(d):
        rebrand_values(d)
        d["CFBundleName"] = PRODUCT_NAME
        # EXPORT COMPLIANCE. ITSAppUsesNonExemptEncryption=false records
        # Daniel's declaration of 2026-10-05, made in App Store Connect for
        # builds 20261005.1531 and .1643: the app uses standard encryption
        # algorithms in addition to Apple's operating system's, and is NOT
        # distributed in France - which App Store Connect stores as "exempt"
        # (usesNonExemptEncryption=false). With the key in the plist that
        # answer no longer has to be given per build.
        # REVISIT BEFORE A FRENCH OR PUBLIC (App Store) RELEASE: distribution
        # in France, or a declaration that differs, needs the questions
        # answered again and possibly our own compliance documentation.
        # Upstream's compliance code belongs to Bitwarden's ASC account and is
        # never used. With our own approved documentation, COMPLIANCE_CODE
        # puts "true" plus that code in instead (ASC rejects "true" without a
        # code of ours: "Invalid Export Compliance Code").
        code = os.environ.get("COMPLIANCE_CODE", "")
        if code:
            d["ITSAppUsesNonExemptEncryption"] = True
            d["ITSEncryptionExportComplianceCode"] = code
        else:
            d["ITSAppUsesNonExemptEncryption"] = False
            d.pop("ITSEncryptionExportComplianceCode", None)
        modes = [m for m in d.get("UIBackgroundModes", []) if m != "remote-notification"]
        if modes:
            d["UIBackgroundModes"] = modes
        else:
            d.pop("UIBackgroundModes", None)
    edit_plist("Bitwarden/Application/Support/Info.plist", app)
    for rel in ["BitwardenAutoFillExtension/Application/Support/Info.plist",
                "BitwardenShareExtension/Application/Support/Info.plist",
                "BitwardenActionExtension/Application/Support/Info.plist"]:
        edit_plist(rel, rebrand_values)


# --- 5. Visible strings ----------------------------------------------------

STRINGS_LINE = re.compile(r'^([ \t]*"(?:[^"\\]|\\.)*"[ \t]*=[ \t]*")(.*)(";[ \t]*)$', re.M)
DICT_STRING = re.compile(r"(<string>)(.*?)(</string>)")


def debrand(m):
    """Keep the key / markup (group 1 and 3), rebrand the value (group 2)."""
    # (?<!@): leave %#@BitwardenSomething@ plural variable names alone.
    return m.group(1) + re.sub(r"(?<!@)Bitwarden", PRODUCT_NAME, m.group(2)) + m.group(3)


def localizations():
    base = "BitwardenResources/Localizations"
    for lproj in sorted(os.listdir(p(base))):
        for name in ("Localizable.strings", "Localizable.stringsdict", "InfoPlist.strings"):
            rel = os.path.join(base, lproj, name)
            if not os.path.exists(p(rel)):
                continue
            text = read(rel)
            if name.endswith(".stringsdict"):
                out = DICT_STRING.sub(debrand, text)
            else:
                out = STRINGS_LINE.sub(debrand, text)
            if lproj == "nl.lproj":
                # The vault's own word in Dutch (Daniel, 2026-10-05): not
                # "hoofdwachtwoord" but "Multipass-wachtwoord", as the web
                # vault says it (multipass/web in the Kikaron repo). Values
                # only; a no-op once applied.
                pat = DICT_STRING if name.endswith(".stringsdict") else STRINGS_LINE
                out = pat.sub(lambda m: m.group(1) + MASTER_NL.sub("Multipass-wachtwoord", m.group(2)) + m.group(3), out)
            if out != text:
                write(rel, out)
    replace("BitwardenShared/Core/Tools/Utilities/CredentialManagerFactory.swift",
            'exporterDisplayName: "Bitwarden",', f'exporterDisplayName: "{PRODUCT_NAME}",')


