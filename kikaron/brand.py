#!/usr/bin/env python3
"""Apply the Kikaron Multipass branding to a checkout of bitwarden/ios.

Run through kikaron/brand.sh. Every edit is either a plist/strings
transformation or an exact-text replacement that is skipped when already
applied and FAILS LOUDLY when its anchor is gone (so a new upstream tag that
moved the code is noticed, never silently half-branded). Idempotent.
"""
import os
import plistlib
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TEAM_ID = os.environ.get("TEAM_ID", "MS3X6X39RW")
BUNDLE_ID = os.environ.get("BUNDLE_ID", "com.kikaron.multipass")
APP_GROUP = "group." + BUNDLE_ID
STORE_NAME = os.environ.get("STORE_NAME", "Kikaron Multipass")
PRODUCT_NAME = os.environ.get("PRODUCT_NAME", "Multipass")
SERVER_HOST = os.environ.get("SERVER_HOST", "multipass.kikaron.com")
MARKETING_VERSION = os.environ.get("MARKETING_VERSION", "")

failures = []


def p(rel):
    return os.path.join(ROOT, rel)


def read(rel):
    with open(p(rel), encoding="utf-8") as fh:
        return fh.read()


def write(rel, text):
    with open(p(rel), "w", encoding="utf-8") as fh:
        fh.write(text)


def replace(rel, old, new):
    """Exact replacement; skip if `new` is already there, fail if neither."""
    text = read(rel)
    if old in text:
        write(rel, text.replace(old, new))
    elif new not in text:
        failures.append(f"{rel}: anchor not found:\n    {old!r}")


def remove(rel):
    if os.path.exists(p(rel)):
        os.remove(p(rel))


def edit_plist(rel, fn):
    with open(p(rel), "rb") as fh:
        data = plistlib.load(fh)
    fn(data)
    with open(p(rel), "wb") as fh:
        plistlib.dump(data, fh, sort_keys=True)


BRAND = re.compile(r"\bBitwarden\b")


def rebrand_values(obj):
    """Replace the word Bitwarden in every string *value* (never keys)."""
    if isinstance(obj, dict):
        for k, v in obj.items():
            obj[k] = rebrand_values(v)
        return obj
    if isinstance(obj, list):
        return [rebrand_values(v) for v in obj]
    if isinstance(obj, str):
        return BRAND.sub(PRODUCT_NAME, obj)
    return obj


# --- 1. Signing / identity: upstream's Local-bwpm.xcconfig seam -------------

def local_xcconfig():
    lines = [
        "// Generated by kikaron/brand.sh - do not edit.",
        "CODE_SIGN_STYLE = Automatic",
        "CODE_SIGN_IDENTITY = Apple Development",
        f"DEVELOPMENT_TEAM = {TEAM_ID}",
        "ORGANIZATION_IDENTIFIER = " + BUNDLE_ID.rsplit(".", 1)[0],
        f"BASE_BUNDLE_ID = {BUNDLE_ID}",
        # Upstream shares a second group with Bitwarden Authenticator; we have
        # no Authenticator, so point it at our own group.
        f"SHARED_APP_GROUP_IDENTIFIER = {APP_GROUP}",
        "APPICON_NAME = AppIcon",
        f"BMPW_BUNDLE_DISPLAY_NAME = {STORE_NAME}",
        "PROVISIONING_PROFILE_SPECIFIER =",
        "PROVISIONING_PROFILE_SPECIFIER_ACTION_EXTENSION =",
        "PROVISIONING_PROFILE_SPECIFIER_AUTOFILL_EXTENSION =",
        "PROVISIONING_PROFILE_SPECIFIER_NOTIFICATION_EXTENSION =",
        "PROVISIONING_PROFILE_SPECIFIER_SHARE_EXTENSION =",
    ]
    if MARKETING_VERSION:
        lines.append(f"MARKETING_VERSION = {MARKETING_VERSION}")
    write("Configs/Local-bwpm.xcconfig", "\n".join(lines) + "\n")


# --- 2. Project: no watch app, no notification extension, no Firebase ------

def project():
    rel = "project-pm.yml"
    replace(rel, "      - path: Bitwarden/Application/Support/GoogleService-Info.plist\n"
                 "        buildPhase: resources\n", "")
    replace(rel, "      - target: BitwardenNotificationExtension\n"
                 "      - target: BitwardenShareExtension\n"
                 "      - target: BitwardenWatchApp\n",
                 "      - target: BitwardenShareExtension\n")
    replace(rel, "      - package: BitwardenSdk\n"
                 "      - package: Firebase\n"
                 "        product: FirebaseCrashlytics\n"
                 "    preBuildScripts:\n"
                 "      - path: Scripts/update_acknowledgements.sh\n",
                 "      - package: BitwardenSdk\n"
                 "    preBuildScripts:\n"
                 "      - path: Scripts/update_acknowledgements.sh\n")
    # Crashlytics would report to Bitwarden's Firebase project: log locally.
    replace("Bitwarden/Application/Services/ErrorReporter/ErrorReporterFactory.swift",
            "        #if DEBUG\n        OSLogErrorReporter()\n        #else\n"
            "        CrashlyticsErrorReporter.shared\n        #endif\n",
            "        OSLogErrorReporter() // Kikaron: no Crashlytics\n")
    remove("Bitwarden/Application/Services/ErrorReporter/CrashlyticsErrorReporter.swift")
    remove("Bitwarden/Application/Support/GoogleService-Info.plist")


# --- 3. Entitlements --------------------------------------------------------

def entitlements():
    def app(d):
        d.pop("aps-environment", None)  # no push for now; the app syncs on open
        d.pop("com.apple.developer.nfc.readersession.formats", None)
        d.pop("com.apple.developer.ubiquity-container-identifiers", None)
        d["com.apple.developer.associated-domains"] = [f"webcredentials:{SERVER_HOST}"]
        d["com.apple.security.application-groups"] = ["group.$(BASE_BUNDLE_ID)"]
    edit_plist("Bitwarden/Application/Support/Bitwarden.entitlements", app)


# --- 4. Info.plists: names, export compliance, background modes -------------

def info_plists():
    def app(d):
        rebrand_values(d)
        d["CFBundleName"] = PRODUCT_NAME
        # Upstream's code belongs to Bitwarden's ASC account. Keep declaring
        # non-exempt encryption (true); the code comes from our own ASC answer.
        d["ITSAppUsesNonExemptEncryption"] = True
        d.pop("ITSEncryptionExportComplianceCode", None)
        modes = [m for m in d.get("UIBackgroundModes", []) if m != "remote-notification"]
        if modes:
            d["UIBackgroundModes"] = modes
        else:
            d.pop("UIBackgroundModes", None)
    edit_plist("Bitwarden/Application/Support/Info.plist", app)
    for rel in ["BitwardenAutoFillExtension/Application/Support/Info.plist",
                "BitwardenShareExtension/Application/Support/Info.plist",
                "BitwardenActionExtension/Application/Support/Info.plist"]:
        edit_plist(rel, rebrand_values)


# --- 5. Visible strings ----------------------------------------------------

STRINGS_LINE = re.compile(r'^([ \t]*"(?:[^"\\]|\\.)*"[ \t]*=[ \t]*")(.*)(";[ \t]*)$', re.M)
DICT_STRING = re.compile(r"(<string>)(.*?)(</string>)")


def debrand(m):
    """Keep the key / markup (group 1 and 3), rebrand the value (group 2)."""
    return m.group(1) + m.group(2).replace("Bitwarden", PRODUCT_NAME) + m.group(3)


def localizations():
    base = "BitwardenResources/Localizations"
    for lproj in sorted(os.listdir(p(base))):
        for name in ("Localizable.strings", "Localizable.stringsdict", "InfoPlist.strings"):
            rel = os.path.join(base, lproj, name)
            if not os.path.exists(p(rel)):
                continue
            text = read(rel)
            if name.endswith(".stringsdict"):
                out = DICT_STRING.sub(debrand, text)
            else:
                out = STRINGS_LINE.sub(debrand, text)
            if out != text:
                write(rel, out)
    replace("BitwardenShared/Core/Tools/Utilities/CredentialManagerFactory.swift",
            'exporterDisplayName: "Bitwarden",', f'exporterDisplayName: "{PRODUCT_NAME}",')


# --- 6. Default server: preselect self-hosted at SERVER_HOST ----------------

def default_server():
    write("BitwardenKit/Core/Platform/Models/Domain/EnvironmentURLData+Kikaron.swift",
          "import Foundation\n\n"
          "// Kikaron Multipass: the server a fresh install points at. Generated by kikaron/brand.sh.\n"
          "public extension EnvironmentURLData {\n"
          "    /// The Multipass server, preselected (as self-hosted) on first launch.\n"
          f'    static let defaultMultipass = EnvironmentURLData(base: URL(string: "https://{SERVER_HOST}")!)\n'
          "}\n")
    rel = "BitwardenShared/Core/Platform/Services/EnvironmentService.swift"
    replace(rel, "_environmentURLs = EnvironmentURLs(environmentURLData: .defaultUS)",
                 "_environmentURLs = EnvironmentURLs(environmentURLData: .defaultMultipass)")
    replace(rel, "            urls = .defaultUS\n", "            urls = .defaultMultipass\n")
    rel = "BitwardenShared/UI/Auth/Utilities/RegionHelper.swift"
    replace(rel, "await delegate?.setRegion(.unitedStates, .defaultUS)",
                 "await delegate?.setRegion(.selfHosted, .defaultMultipass)")
    replace(rel, "to: .selfHosted(currentRegion: currentRegion ?? .unitedStates),",
                 "to: .selfHosted(currentRegion: currentRegion ?? .selfHosted),")
    replace("BitwardenShared/UI/Auth/Landing/LandingState.swift",
            "        region: RegionType = .unitedStates,\n",
            "        region: RegionType = .selfHosted,\n")
    # Only self-hosted in the region picker: no Bitwarden cloud regions.
    replace("BitwardenShared/Core/Platform/Models/Enum/RegionType.swift",
            "        case .europe, .gov, .selfHosted, .unitedStates: true\n"
            "        case .internal: false\n",
            "        case .selfHosted: true\n"
            "        case .europe, .gov, .internal, .unitedStates: false\n")


def main():
    local_xcconfig()
    project()
    entitlements()
    info_plists()
    localizations()
    default_server()
    if failures:
        print("kikaron/brand.py: upstream moved, update the anchors:", file=sys.stderr)
        for f in failures:
            print("  " + f, file=sys.stderr)
        sys.exit(1)
    print("branding applied")


if __name__ == "__main__":
    main()
